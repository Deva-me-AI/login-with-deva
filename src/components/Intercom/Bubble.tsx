import { useDevaContext } from "@/DevaContext";
import type { ChatMessageAuthor, Persona } from "@/server";
import { cn } from "@/lib/utils";

import {
  Tooltip,
  TooltipContent,
  TooltipProvider,
  TooltipTrigger,
} from "@/components/ui/tooltip";
import { Card, CardContent } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { dateToTime } from "@/lib/time";
import { linkMentionsForMarkdown } from "@/lib/markdown-format";
import { Markdown } from "../Markdown";

// const NOTE_REGEX = /\[\[([^\]]+)\]\]/g;

interface Props {
  author_type: ChatMessageAuthor;
  persona?: {
    id: string;
    username: string;
    display_name?: string | null;
    user_id?: string | null;
  };
  response: string;
  createdAt: Date;
  reply?: {
    text?: string;
    persona?: Persona;
    author_type: "USER" | "BOT" | "SYSTEM";
  } | null;
  className?: string;
  hasPublishedVariant?: boolean;
}

interface IHighlight {
  children: string;
}

export const Highlight = ({ children }: IHighlight) => {
  return (
    <Badge
      variant="outline"
      className={cn(
        children.trim().startsWith("@") || children.trim().startsWith("#")
          ? "deva-border-[#CEF049]/20 deva-text-[#CEF049]"
          : "deva-border-[#f0b733]/20 deva-text-[#f0b733]",
      )}
    >
      {children}
    </Badge>
  );
};

export const ChatBubble = ({
  author_type,
  persona,
  response,
  createdAt,
  reply,
  className,
  hasPublishedVariant = false,
}: Props) => {
  const { user } = useDevaContext();
  const userPersona = user?.persona;

  return (
    <div
      className={cn(
        "deva-flex deva-flex-grow deva-flex-col deva-whitespace-pre-wrap",
        className,
      )}
    >
      {author_type === "BOT" ? (
        <div
          className={cn("deva-flex deva-items-center deva-whitespace-nowrap", {
            "deva-text-sea-700": persona?.id !== userPersona?.id,
          })}
        >
          <div className="deva-max-w-[6rem] deva-overflow-hidden deva-overflow-ellipsis md:deva-max-w-[15rem]">
            {persona?.display_name ?? persona?.username ?? null}&nbsp;
          </div>
          <TooltipProvider>
            <Tooltip>
              <TooltipTrigger asChild>
                <span className="deva-relative deva-flex deva-items-center deva-pt-[2px]">
                  {persona?.user_id ? "🫶" : "🤖"}
                </span>
              </TooltipTrigger>
              <TooltipContent>
                {persona?.user_id
                  ? "This Deva AI has been claimed by a person"
                  : "This Deva AI has not yet been claimed"}
              </TooltipContent>
            </Tooltip>
          </TooltipProvider>
          &nbsp;
          <span className="deva-max-w-[7rem] deva-overflow-y-hidden deva-overflow-x-scroll deva-text-[#6B7584] md:deva-max-w-[16rem]">
            <TooltipProvider>
              <Tooltip>
                <TooltipTrigger asChild>
                  <div className="deva-relative deva-cursor-help">
                    <span>
                      {`${hasPublishedVariant ? "!" : "@"}${persona?.username}`}
                    </span>
                  </div>
                </TooltipTrigger>
                <TooltipContent>
                  {hasPublishedVariant
                    ? "This content was generated by a person"
                    : "This content was generated by an AI"}
                </TooltipContent>
              </Tooltip>
            </TooltipProvider>
          </span>
        </div>
      ) : (
        <div
          className={cn({
            "deva-w-[180px] deva-overflow-hidden deva-overflow-ellipsis deva-whitespace-nowrap deva-text-sea-700 md:deva-w-full":
              userPersona?.id !== persona?.id,
          })}
        >
          {userPersona?.id !== persona?.id && persona?.username}
          {persona && userPersona?.id !== persona?.id && (
            <span className="deva-text-[#6B7584]">
              &nbsp;{`!${persona?.username}`}
            </span>
          )}
        </div>
      )}

      {reply?.text?.trim() ? (
        <Card
          data-testid="ChatMessageReplyQuote"
          className={cn(
            "-deva-mx-2 -deva-mr-10 deva-mb-2 deva-flex deva-min-h-[20px] deva-flex-col deva-items-start deva-border-0 deva-shadow-sm",
            {
              "deva-mt-1": !(
                userPersona?.id === persona?.id && author_type === "USER"
              ),
              "!deva-bg-[#2e46c0]":
                userPersona?.id === persona?.id && author_type === "USER",
            },
          )}
        >
          <CardContent className="deva-p-4">
            <div className="deva-font-medium">
              {reply.persona?.id === userPersona?.id
                ? "You"
                : (reply?.persona?.display_name ?? reply?.persona?.username)}
              &nbsp;
              {reply?.author_type === "USER" ? "🫶" : "🤖"}
            </div>

            <div className="deva-line-clamp-1">
              <Markdown>{linkMentionsForMarkdown(reply.text.trim())}</Markdown>
            </div>
          </CardContent>
        </Card>
      ) : null}

      <div
        data-testid="ChatMessageText"
        className="deva-mr-4 deva-flex deva-min-h-[20px] deva-flex-col deva-items-start deva-gap-4 [overflow-wrap:anywhere]"
      >
        <Markdown>
          {linkMentionsForMarkdown(response.toString().trim())}
        </Markdown>
      </div>

      <span
        className={cn(
          "deva-absolute deva-bottom-[0.6rem] deva-right-4 deva-h-5 deva-text-[14px]",
          {
            // message on left (bot other others)
            "deva-text-lynch-600":
              persona?.id !== persona?.id || author_type === "BOT",
            // message on right (user)
            "deva-text-white deva-opacity-60":
              persona?.id === persona?.id && author_type === "USER",
          },
        )}
      >
        {dateToTime(new Date(createdAt))}
      </span>
    </div>
  );
};
