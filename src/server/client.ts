import createClient from "openapi-fetch";
import type { paths } from "./open-api-schema"; // generated by openapi-typescript
import { HashingLibrary } from "./hasher";

const baseUrl = "https://localhost:9000/api";

export class DevaClient {
  private appId: string;
  private appKey: string;
  private client: ReturnType<typeof createClient<paths>>;
  private hasher: HashingLibrary;

  constructor(appId: string, appKey: string, secretKey?: string) {
    this.appId = appId;
    this.appKey = appKey;

    this.client = createClient<paths>({
      baseUrl,
    });
    this.hasher = new HashingLibrary(secretKey);
  }

  async verifyAuthToken(_token: string) {
    const { data: token } = await this.client.GET("/auth/verification_token", {
      params: {
        query: {
          identifier: "",
          token: this.hasher.createHash(_token),
        },
      },
    });
  }
}
